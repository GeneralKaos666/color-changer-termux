use termux_colors::model::colors::{Rgb, TerminalColors};
use termux_colors::persist::colors_io::{read_colors, write_colors};

#[test]
fn writing_the_link_edits_the_target_and_keeps_the_link() {
    let dir = tempfile::tempdir().unwrap();
    let target = dir.path().join("Theme.properties");
    std::fs::write(&target, "background=#000000\n").unwrap();
    let link = dir.path().join("colors.properties");
    std::os::unix::fs::symlink(&target, &link).unwrap();

    let mut colors = read_colors(&link).unwrap();
    colors.background = Rgb::new(1, 2, 3);
    write_colors(&link, &colors, true).unwrap();

    assert!(link.symlink_metadata().unwrap().file_type().is_symlink());
    assert!(
        std::fs::read_to_string(&target)
            .unwrap()
            .contains("background=#010203")
    );
}

#[test]
fn write_creates_parent_directories() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("custom/deep/Theme.properties");
    write_colors(&path, &TerminalColors::default(), false).unwrap();
    assert!(path.is_file());
}

#[test]
fn a_missing_file_reads_as_defaults() {
    let dir = tempfile::tempdir().unwrap();
    let missing = dir.path().join("colors.properties");
    assert_eq!(read_colors(&missing).unwrap(), TerminalColors::default());
    assert!(!missing.exists());
}

#[test]
fn an_unreadable_path_reads_as_an_error() {
    let dir = tempfile::tempdir().unwrap();
    // A directory exists but is not a readable file.
    assert!(read_colors(dir.path()).is_err());
}

#[test]
fn preserve_keeps_comments_and_extras_while_updating_colours() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("colors.properties");
    std::fs::write(
        &path,
        "# mine\nbackground=#000000\nselection-background=#333333\ncolor3=#111111\n",
    )
    .unwrap();

    let mut colors = read_colors(&path).unwrap();
    colors.background = Rgb::new(0x12, 0x34, 0x56);
    write_colors(&path, &colors, true).unwrap();

    let text = std::fs::read_to_string(&path).unwrap();
    assert!(text.starts_with("# mine\n"));
    assert!(text.contains("background=#123456\n"));
    assert!(text.contains("selection-background=#333333\n"));
    // The palette entry that was read is written back unchanged, and a managed
    // key the file never had is appended.
    assert!(text.contains("color3=#111111\n"));
    assert!(text.contains("cursor=#ffffff\n"));
}

#[test]
fn without_preserve_a_fresh_document_replaces_the_old_one() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("colors.properties");
    std::fs::write(&path, "# mine\nunknown=1\n").unwrap();

    write_colors(&path, &TerminalColors::default(), false).unwrap();

    let text = std::fs::read_to_string(&path).unwrap();
    assert!(text.starts_with("# Generated by termux-colors\n"));
    assert!(!text.contains("# mine"));
    assert!(!text.contains("unknown=1"));
    assert_eq!(
        text,
        termux_colors::persist::colors_io::render_colors(&TerminalColors::default())
    );
}
