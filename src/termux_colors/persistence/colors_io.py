"""Read and write Termux ``colors.properties`` files."""

from __future__ import annotations

from pathlib import Path

from ..models.colors import (
    PALETTE_KEYS,
    DEFAULT_PALETTE,
    TerminalColors,
)
from .properties import parse_active, set_value

MANAGED_KEYS = ("background", "foreground", "cursor", *PALETTE_KEYS)


def parse_colors(text: str) -> TerminalColors:
    """Parse *text* into a :class:`TerminalColors`, tolerating partial files."""
    pairs = parse_active(text)
    palette = [pairs.get(key, DEFAULT_PALETTE[index]) for index, key in enumerate(PALETTE_KEYS)]
    extra = {key: value for key, value in pairs.items() if key not in MANAGED_KEYS}
    return TerminalColors(
        background=pairs.get("background", "#000000"),
        foreground=pairs.get("foreground", "#ffffff"),
        cursor=pairs.get("cursor", pairs.get("foreground", "#ffffff")),
        palette=palette,
        extra=extra,
    )


def render_colors(colors: TerminalColors) -> str:
    """Render a complete, freshly generated ``colors.properties`` body."""
    lines = [
        "# Generated by termux-colors",
        f"background={colors.background}",
        f"foreground={colors.foreground}",
        f"cursor={colors.cursor}",
        "",
    ]
    for key, value in zip(PALETTE_KEYS, colors.palette):
        lines.append(f"{key}={value}")
    for key, value in colors.extra.items():
        lines.append(f"{key}={value}")
    return "\n".join(lines) + "\n"


def update_colors_text(text: str, colors: TerminalColors) -> str:
    """Update managed keys in *text* in place, keeping comments and extras."""
    result = text if text.strip() else render_colors(colors)
    for key, value in colors.as_dict().items():
        result = set_value(result, key, value)
    return result


def read_colors(path: Path) -> TerminalColors:
    """Read and parse a colours file, returning defaults when absent."""
    if not path.exists():
        return TerminalColors(palette=list(DEFAULT_PALETTE))
    return parse_colors(path.read_text(encoding="utf-8", errors="replace"))


def write_colors(path: Path, colors: TerminalColors, preserve: bool = True) -> None:
    """Write *colors* to *path*.

    When *preserve* is true and the file exists, comments and unrelated keys
    are kept.  If *path* is a symlink the write follows it, so the link target
    (the real theme file) is what changes.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if preserve and path.exists():
        content = update_colors_text(path.read_text(encoding="utf-8", errors="replace"), colors)
    else:
        content = render_colors(colors)
    path.write_text(content, encoding="utf-8")
