//! Read and write Termux `colors.properties` files.
//!
//! The file is the terminal's colour scheme: nineteen keys this application
//! owns (`background`, `foreground`, `cursor` and `color0`..`color15`) plus
//! whatever else Termux or the user put there. Reading tolerates partial or
//! malformed files by falling back to [`DEFAULT_PALETTE`] and the standard
//! black-on-white colours; writing can either generate a fresh file or edit the
//! managed keys in place so comments and unrelated keys survive.

use std::path::Path;

use crate::error::Result;
use crate::model::colors::{ColorField, DEFAULT_PALETTE, PALETTE_KEYS, Rgb, TerminalColors};
use crate::persist::properties::{parse_active, set_value};

/// The `colors.properties` keys this application owns.
///
/// Every other key in a file is preserved verbatim in
/// [`TerminalColors::extra`].
pub const MANAGED_KEYS: [&str; 19] = [
    "background",
    "foreground",
    "cursor",
    PALETTE_KEYS[0],
    PALETTE_KEYS[1],
    PALETTE_KEYS[2],
    PALETTE_KEYS[3],
    PALETTE_KEYS[4],
    PALETTE_KEYS[5],
    PALETTE_KEYS[6],
    PALETTE_KEYS[7],
    PALETTE_KEYS[8],
    PALETTE_KEYS[9],
    PALETTE_KEYS[10],
    PALETTE_KEYS[11],
    PALETTE_KEYS[12],
    PALETTE_KEYS[13],
    PALETTE_KEYS[14],
    PALETTE_KEYS[15],
];

/// Returns the key/value pairs of `text` with each key appearing once.
///
/// [`parse_active`] reports duplicate keys once per occurrence so callers can
/// see the file as written. A colour lookup needs one answer per key, and the
/// file wins the same way it does for Termux: the last occurrence supplies the
/// value while the key keeps the position of its first appearance.
fn dedupe(pairs: Vec<(String, String)>) -> Vec<(String, String)> {
    let mut unique: Vec<(String, String)> = Vec::with_capacity(pairs.len());
    for (key, value) in pairs {
        match unique.iter_mut().find(|(existing, _)| *existing == key) {
            Some(entry) => entry.1 = value,
            None => unique.push((key, value)),
        }
    }
    unique
}

/// Returns the value stored under `key`, if the file has one.
fn lookup<'a>(pairs: &'a [(String, String)], key: &str) -> Option<&'a str> {
    pairs
        .iter()
        .find(|(existing, _)| existing == key)
        .map(|(_, value)| value.as_str())
}

/// Parses `text` into [`TerminalColors`], tolerating partial files.
///
/// A managed key that is absent or does not hold a valid hex colour falls back
/// to its default. `cursor` falls back to the parsed `foreground` first, and
/// only then to white, so a file that sets just a foreground still gets a
/// matching cursor.
pub fn parse_colors(text: &str) -> TerminalColors {
    let pairs = dedupe(parse_active(text));
    let resolve =
        |key: &str, fallback: Rgb| lookup(&pairs, key).and_then(Rgb::parse).unwrap_or(fallback);

    let background = resolve("background", Rgb::new(0x00, 0x00, 0x00));
    let foreground = resolve("foreground", Rgb::new(0xff, 0xff, 0xff));
    let cursor = resolve("cursor", foreground);

    let mut palette = DEFAULT_PALETTE;
    for (index, key) in PALETTE_KEYS.iter().enumerate() {
        palette[index] = resolve(key, DEFAULT_PALETTE[index]);
    }

    let extra = pairs
        .into_iter()
        .filter(|(key, _)| !MANAGED_KEYS.contains(&key.as_str()))
        .collect();

    TerminalColors {
        background,
        foreground,
        cursor,
        palette,
        extra,
    }
}

/// Renders a complete, freshly generated `colors.properties` body.
///
/// The layout is the header comment, the three non-palette colours, a blank
/// line, `color0`..`color15`, then the preserved extra pairs in their stored
/// order. The result always ends with exactly one newline.
pub fn render_colors(colors: &TerminalColors) -> String {
    let mut lines = vec![
        "# Generated by termux-colors".to_owned(),
        format!("background={}", colors.background),
        format!("foreground={}", colors.foreground),
        format!("cursor={}", colors.cursor),
        String::new(),
    ];
    for (key, color) in PALETTE_KEYS.iter().zip(&colors.palette) {
        lines.push(format!("{key}={color}"));
    }
    for (key, value) in &colors.extra {
        lines.push(format!("{key}={value}"));
    }

    let mut text = lines.join("\n");
    text.push('\n');
    text
}

/// Updates the managed keys in `text` in place, keeping comments and extras.
///
/// Text that is empty or only whitespace has nothing worth preserving, so a
/// fresh document is rendered instead. Everything else is edited one key at a
/// time with [`set_value`], which keeps line order, indentation, separator
/// style and line endings.
pub fn update_colors_text(text: &str, colors: &TerminalColors) -> String {
    let mut result = if text.trim().is_empty() {
        render_colors(colors)
    } else {
        text.to_owned()
    };
    for field in ColorField::ALL {
        result = set_value(&result, &field.key(), &colors.field(field).to_hex());
    }
    for (key, value) in &colors.extra {
        result = set_value(&result, key, value);
    }
    result
}

/// Reads `path` as UTF-8 text, replacing bytes that are not valid UTF-8.
///
/// The file is read as bytes rather than through
/// [`std::fs::read_to_string`] so a Latin-1 comment cannot stop a colour file
/// from loading; the replacement matches the Python implementation's
/// `errors="replace"`.
fn read_text(path: &Path) -> Result<String> {
    let bytes = std::fs::read(path)?;
    Ok(String::from_utf8_lossy(&bytes).into_owned())
}

/// Reads and parses a colours file, returning defaults when it is absent.
///
/// A missing file is not an error: an installation that has never been
/// customised simply has no `colors.properties` yet. An error is returned only
/// when the path exists but cannot be read. Reads follow symlinks, so a link to
/// a theme file yields that theme.
pub fn read_colors(path: &Path) -> Result<TerminalColors> {
    if !path.exists() {
        return Ok(TerminalColors::default());
    }
    Ok(parse_colors(&read_text(path)?))
}

/// Writes `colors` to `path`, creating parent directories as needed.
///
/// When `preserve` is true and the file already exists, its current text is
/// updated with [`update_colors_text`] so comments and unrelated keys survive;
/// otherwise a fresh document is rendered. The write follows symlinks, so
/// writing a `colors.properties` link edits the theme file it points at and
/// leaves the link in place.
pub fn write_colors(path: &Path, colors: &TerminalColors, preserve: bool) -> Result<()> {
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        std::fs::create_dir_all(parent)?;
    }
    let content = if preserve && path.exists() {
        update_colors_text(&read_text(path)?, colors)
    } else {
        render_colors(colors)
    };
    std::fs::write(path, content)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const PARTIAL: &str = "background=#0f0c1a\nforeground=#f8f8f2\ncolor0=#0f0c1a\ncolor1=#ff3366\nselection-background=#333333\n";

    #[test]
    fn partial_files_fall_back_to_defaults() {
        let c = parse_colors(PARTIAL);
        assert_eq!(c.background.to_hex(), "#0f0c1a");
        assert_eq!(c.cursor.to_hex(), "#f8f8f2"); // falls back to foreground
        assert_eq!(c.palette[2], DEFAULT_PALETTE[2]);
    }

    #[test]
    fn cursor_falls_back_to_white_without_foreground() {
        assert_eq!(parse_colors("").cursor.to_hex(), "#ffffff");
    }

    #[test]
    fn extras_keep_file_order() {
        let c = parse_colors("background=#000000\nzzz=1\naaa=2\n");
        assert_eq!(
            c.extra,
            vec![("zzz".into(), "1".into()), ("aaa".into(), "2".into())]
        );
    }

    #[test]
    fn render_writes_header_and_key_order() {
        let out = render_colors(&TerminalColors::default());
        assert!(out.starts_with("# Generated by termux-colors\nbackground=#000000\nforeground=#ffffff\ncursor=#ffffff\n\ncolor0=#000000\n"));
        assert!(out.ends_with("color15=#eeeeee\n"));
    }

    #[test]
    fn update_keeps_comments_and_extras() {
        let text = "# mine\nbackground=#000000\ncolor3=#111111\nselection-background=#333333\n";
        let out = update_colors_text(text, &TerminalColors::default());
        assert!(out.starts_with("# mine\n"));
        assert!(out.contains("selection-background=#333333\n"));
        assert!(out.contains("color3=#c4a000\n"));
        assert!(out.contains("background=#000000\n"));
    }

    #[test]
    fn blank_text_renders_fresh() {
        assert_eq!(
            update_colors_text("  \n", &TerminalColors::default()),
            render_colors(&TerminalColors::default())
        );
    }

    #[test]
    fn managed_keys_are_the_nineteen_owned_colours() {
        assert_eq!(MANAGED_KEYS.len(), 19);
        assert_eq!(&MANAGED_KEYS[..3], &["background", "foreground", "cursor"]);
        assert_eq!(MANAGED_KEYS[3], "color0");
        assert_eq!(MANAGED_KEYS[18], "color15");
        assert!(!MANAGED_KEYS.contains(&"selection-background"));
    }

    #[test]
    fn invalid_hex_falls_back_to_defaults() {
        let c = parse_colors(
            "background=nope\nforeground=#zzzzzz\ncursor=also-bad\ncolor1=oops\ncolor15=#abc\n",
        );
        assert_eq!(c.background, Rgb::new(0x00, 0x00, 0x00));
        assert_eq!(c.foreground, Rgb::new(0xff, 0xff, 0xff));
        assert_eq!(c.cursor, Rgb::new(0xff, 0xff, 0xff));
        assert_eq!(c.palette[1], DEFAULT_PALETTE[1]);
        // Valid short forms are still accepted.
        assert_eq!(c.palette[15], Rgb::new(0xaa, 0xbb, 0xcc));
    }

    #[test]
    fn a_valid_cursor_wins_over_the_foreground() {
        let c = parse_colors("foreground=#112233\ncursor=#445566\n");
        assert_eq!(c.cursor, Rgb::new(0x44, 0x55, 0x66));
        let c = parse_colors("foreground=#112233\n");
        assert_eq!(c.cursor, Rgb::new(0x11, 0x22, 0x33));
    }

    #[test]
    fn the_last_duplicate_key_wins_but_keeps_its_position() {
        let c = parse_colors("zzz=1\nbackground=#111111\nzzz=2\nbackground=#222222\n");
        assert_eq!(c.background, Rgb::new(0x22, 0x22, 0x22));
        assert_eq!(c.extra, vec![("zzz".into(), "2".into())]);
    }

    #[test]
    fn render_appends_extras_after_the_palette() {
        let colors = TerminalColors {
            extra: vec![("selection-background".into(), "#333333".into())],
            ..Default::default()
        };
        let out = render_colors(&colors);
        assert!(out.ends_with("color15=#eeeeee\nselection-background=#333333\n"));
    }

    #[test]
    fn update_rewrites_managed_keys_and_keeps_unknown_lines() {
        let colors = TerminalColors {
            background: Rgb::new(1, 2, 3),
            palette: {
                let mut palette = DEFAULT_PALETTE;
                palette[0] = Rgb::new(4, 5, 6);
                palette
            },
            extra: vec![("extra-key".into(), "kept".into())],
            ..Default::default()
        };
        let out = update_colors_text("extra-key = kept\n# note\n", &colors);
        assert!(out.starts_with("extra-key = kept\n# note\n"));
        assert!(out.contains("background=#010203\n"));
        assert!(out.contains("color0=#040506\n"));
    }
}
